def seed_default_videos(db: Session) -> int:
    """表为空时写入预置视频，返回新增条数"""
    if db.query(Video).count() > 0:
        return 0
    for item in DEFAULT_VIDEOS:
        db.add(Video(status=1, **item))
    db.flush()
    return len(DEFAULT_VIDEOS)
